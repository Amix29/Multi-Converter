async function imageCase(browserInstance, options) {
  const input = path.join(fixtureRoot, `${options.id}.png`);
  const page = await browserInstance.newPage({ viewport: { width: 2400, height: 560 } });
  try {
    const family = options.language === "ja"
      ? "'Meiryo','Yu Gothic UI','Yu Gothic',sans-serif"
      : "Arial,sans-serif";
    const background = options.background === "noise"
      ? "radial-gradient(circle at 20% 30%,#bbb 0 1px,transparent 2px),radial-gradient(circle at 70% 60%,#aaa 0 1px,transparent 2px),#fff"
      : options.background ?? "#fff";
    const text = options.blank ? "" : escapeHtml(options.expected).replaceAll("\n", "<br>");
    await page.setContent(`<!doctype html><style>
      html,body{margin:0;width:100%;height:100%;background:${background}}
      body{display:grid;place-items:center;overflow:hidden;color:${options.color ?? "#111"};font:64px ${family}}
      div{white-space:${options.multiline ? "normal" : "nowrap"};line-height:1.35;text-align:left;transform:${options.transform ?? "none"};filter:${options.filter ?? "none"};transform-origin:center}
    </style><div>${text}</div>`);
    await page.screenshot({ path: input, animations: "disabled" });
  } finally {
    await page.close();
  }
  return entry({
    id: options.id,
    category: options.category ?? "clean",
    kind: "ocr-image",
    language: options.language,
    input,
    expected: options.expected,
    threshold: options.threshold,
  });
}

async function groupedImageCases(browserInstance, groupId, definitions) {
  const input = path.join(fixtureRoot, `${groupId}.png`);
  const page = await browserInstance.newPage({ viewport: { width: 2000, height: Math.max(560, definitions.length * 190) } });
  try {
    const rows = definitions.map((definition) => {
      const family = definition.language === "ja"
        ? "'Meiryo','Yu Gothic UI','Yu Gothic',sans-serif"
        : "Arial,sans-serif";
      const background = definition.background === "noise"
        ? "radial-gradient(circle at 20% 30%,#aaa 0 1px,transparent 2px),radial-gradient(circle at 70% 60%,#aaa 0 1px,transparent 2px),#fff"
        : definition.background ?? "#fff";
      return `<div style="font-family:${family};color:${definition.color ?? "#111"};background:${background};transform:${definition.transform ?? "none"};filter:${definition.filter ?? "none"}">${escapeHtml(definition.expected)}</div>`;
    }).join("");
    await page.setContent(`<!doctype html><style>
      html,body{margin:0;width:100%;height:100%;background:#fff}
      body{display:flex;flex-direction:column;align-items:center;justify-content:space-evenly;overflow:hidden;font-size:52px}
      div{box-sizing:border-box;max-width:94%;padding:12px 24px;white-space:nowrap;line-height:1.25;transform-origin:center}
    </style>${rows}`);
    await page.screenshot({ path: input, animations: "disabled" });
  } finally {
    await page.close();
  }
  const result = [];
  for (const [blockIndex, definition] of definitions.entries()) {
    result.push(await entry({
      id: definition.id,
      category: definition.category,
      kind: "ocr-image",
      language: definition.language,
      input,
      expected: definition.expected,
      threshold: definition.threshold,
      blockIndex,
    }));
  }
  return result;
}

async function prepareFormatCases() {
  const source = path.join(fixtureRoot, "clean-en.png");
  const formats = [
    ["png", "png"],
    ["jpeg", "jpg"],
    ["webp", "webp"],
    ["tiff", "tiff"],
    ["bmp", "bmp"],
  ];
  const result = [];
  for (const [id, extension] of formats) {
    const output = path.join(fixtureRoot, `normalization-${id}.${extension}`);
    const conversion = spawnSync("ffmpeg", ["-y", "-loglevel", "error", "-i", source, "-frames:v", "1", output], {
      cwd: root,
      stdio: "inherit",
      windowsHide: true,
    });
    if (conversion.status !== 0) throw new Error(`FFmpeg n’a pas produit la fixture ${id}.`);
    result.push(await entry({
      id: `normalization-${id}`,
      category: "image-format",
      kind: "rust-normalization",
      language: "en",
      input: output,
      expected: "Local conversion keeps every document private",
      threshold: 1,
    }));
  }
  return result;
}

async function preparePdfCases(browserInstance) {
  const scannedImage = path.join(fixtureRoot, "clean-fr.png");
  const imageData = `data:image/png;base64,${(await fs.readFile(scannedImage)).toString("base64")}`;
  const definitions = [
    {
      id: "pdf-native",
      expected: "Native PDF text remains directly extractable",
      html: "<main>Native PDF text remains directly extractable</main>",
      expectedSources: ["native"],
    },
    {
      id: "pdf-scanned",
      expected: cleanTexts.fr.join(" "),
      html: `<main><img src="${imageData}" alt=""></main>`,
      expectedSources: ["ocr"],
    },
    {
      id: "pdf-mixed-multipage",
      expected: `Mixed PDF native first page ${cleanTexts.fr.join(" ")}`,
      html: `<main>Mixed PDF native first page</main><main class="page"><img src="${imageData}" alt=""></main>`,
      expectedSources: ["native", "ocr"],
    },
  ];
  const result = [];
  for (const definition of definitions) {
    const input = path.join(fixtureRoot, `${definition.id}.pdf`);
    const page = await browserInstance.newPage();
    try {
      await page.setContent(`<!doctype html><style>
        @page{size:A4;margin:24mm}body{margin:0;font:28px Arial,sans-serif}main{min-height:240mm;display:grid;place-items:center}.page{break-before:page}img{width:100%;height:auto}
      </style>${definition.html}`, { waitUntil: "load" });
      await page.pdf({ path: input, format: "A4", printBackground: true, margin: { top: "0", right: "0", bottom: "0", left: "0" } });
    } finally {
      await page.close();
    }
    result.push(await entry({
      id: definition.id,
      category: "pdf",
      kind: "pdf-hybrid",
      language: definition.id === "pdf-native" ? "en" : "fr",
      input,
      expected: definition.expected,
      threshold: 0.98,
      expectedSources: definition.expectedSources,
    }));
  }
  return result;
}

async function entry(value) {
  const relativeInput = path.relative(root, value.input).replaceAll("\\", "/");
  const bytes = await fs.readFile(value.input);
  return {
    ...value,
    input: relativeInput,
    sha256: createHash("sha256").update(bytes).digest("hex"),
    provenance,
    license,
  };
}

function languageFor(id) {
  if (id.includes("spanish") || id === "inclination-positive") return "es";
  if (id === "inclination-negative") return "de";
  if (id === "noise") return "it";
  if (id === "soft-focus") return "pt";
  return id.includes("perspective") || id === "rotation-positive" ? "fr" : "en";
}

function escapeHtml(value) {
  return value.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;");
}
